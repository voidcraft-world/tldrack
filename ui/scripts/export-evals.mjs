/**
 * The static EVALS export: `npm run export:evals`.
 *
 * 1. `docs/evals/index.html`, the page as ONE file: script, styles and the results inline, so
 *    it opens from the file system and from GitHub Pages alike. A page opened from a file
 *    cannot load a module from a second file, which is why the app's own multi-file build
 *    (`vite.config.ts`) is not what ships here.
 * 2. `docs/evals/figures/<figure>.<theme>.png`, the README's three figures in both themes,
 *    taken from that file as a browser draws it, and `figures/manifest.json`, which stamps them
 *    with the source hash and each PNG's sha256. `--no-figures` skips both, so the figures then
 *    read as stale until a figures run.
 *
 * Re-run it after any change to the page or to `bench/results/`: staleness is a test failure
 * (`evals-export-source.mjs` owns how it is detected).
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vue from '@vitejs/plugin-vue';
import { build } from 'vite';

import {
    EXPORT_PAGE, FIGURES, FIGURES_MANIFEST, SOURCE_META, THEMES, evals_source_hash, sha256_file,
} from './evals-export-source.mjs';

const UI = fileURLToPath(new URL('../', import.meta.url));
/** The figures' width in CSS pixels: a README column shows them at this size, so their text keeps its floors. */
const FIGURE_VIEWPORT = { width: 880, height: 1200 };

/** A script or style body, safe to sit inside its own tag in an HTML file. */
const inline_safe = (text) => text.replaceAll('</script', '<\\/script').replaceAll('</style', '<\\/style').replaceAll('<!--', '<\\!--');

async function build_page() {
    const result = await build({
        configFile: false,
        root: UI,
        base: './',
        logLevel: 'warn',
        plugins: [vue()],
        resolve: { dedupe: ['zod'] },
        build: { write: false, target: 'es2023', modulePreload: false, cssCodeSplit: false, rollupOptions: { input: `${UI}evals.html` } },
    });
    const output = (Array.isArray(result) ? result : [result]).flatMap((part) => part.output);
    const chunks = output.filter((file) => file.type === 'chunk');
    const styles = output.filter((file) => file.type === 'asset' && file.fileName.endsWith('.css'));
    const page = output.find((file) => file.type === 'asset' && file.fileName === 'evals.html');
    const others = output.filter((file) => file.type === 'asset' && file !== page && !styles.includes(file));
    if (!page || chunks.length !== 1 || styles.length !== 1 || others.length > 0) {
        throw new Error(`the page must build to one script and one stylesheet, got: ${output.map((file) => file.fileName).join(', ')}`);
    }

    let html = String(page.source);
    const swap = (pattern, replacement) => {
        if (!pattern.test(html)) throw new Error(`the built page has no ${pattern}`);
        html = html.replace(pattern, () => replacement);
    };
    swap(/<script type="module"[^>]*\ssrc="[^"]*"[^>]*><\/script>/, `<script type="module">${inline_safe(chunks[0].code)}</script>`);
    swap(/<link rel="stylesheet"[^>]*>/, `<style>${inline_safe(String(styles[0].source))}</style>`);
    swap(/<meta charset="UTF-8"\s*\/?>/, `<meta charset="UTF-8" />\n    <!-- Generated by ui/scripts/export-evals.mjs. Do not edit: run \`npm run export:evals\` in ui/. -->\n    <meta name="${SOURCE_META}" content="${evals_source_hash()}">`);
    if (/\s(?:src|href)="\.\//.test(html)) throw new Error('the export still points at a second file');
    return html;
}

async function take_figures() {
    const { chromium } = await import('playwright');
    // Start from none, so a figure the results no longer draw does not linger beside the new ones.
    const dir = new URL('figures/', EXPORT_PAGE);
    for (const old of readdirSync(dir).filter((name) => name.endsWith('.png'))) rmSync(new URL(old, dir));
    const taken = new Set();
    const browser = await chromium.launch();
    try {
        for (const theme of THEMES) {
            const page = await browser.newPage({ viewport: FIGURE_VIEWPORT, deviceScaleFactor: 2 });
            const errors = [];
            page.on('pageerror', (error) => errors.push(String(error)));
            page.on('console', (message) => message.type() === 'error' && errors.push(message.text()));
            await page.goto(`${EXPORT_PAGE.href}?theme=${theme}`);
            // A results file the page refuses draws `.ev-refused` and no panels: say why, not a timeout.
            await page.waitForSelector('.ev-panels, .ev-refused');
            const refused = await page.locator('.ev-refused').allInnerTexts();
            if (refused.length > 0) throw new Error(`the export refuses its results (${theme}):\n${refused.join('\n')}`);
            if (errors.length > 0) throw new Error(`the export logged errors (${theme}):\n${errors.join('\n')}`);
            for (const figure of FIGURES) {
                const panel = page.locator(`[data-figure="${figure}"]`);
                // A panel the results file has no block for is not drawn (`FIGURE_BLOCK`); the test checks which.
                if ((await panel.count()) === 0) continue;
                const file = fileURLToPath(new URL(`figures/${figure}.${theme}.png`, EXPORT_PAGE));
                await panel.screenshot({ path: file });
                taken.add(`${figure}.${theme}.png`);
                console.log(`  ${file}`);
            }
            await page.close();
        }
    } finally {
        await browser.close();
    }
    const figures = Object.fromEntries([...taken].sort().map((file) => [file, sha256_file(new URL(file, FIGURES_MANIFEST))]));
    writeFileSync(FIGURES_MANIFEST, `${JSON.stringify({ source: evals_source_hash(), figures }, null, 2)}\n`);
    console.log(`  ${fileURLToPath(FIGURES_MANIFEST)}`);
}

const html = await build_page();
mkdirSync(new URL('figures/', EXPORT_PAGE), { recursive: true });
writeFileSync(EXPORT_PAGE, html);
console.log(`${fileURLToPath(EXPORT_PAGE)}  ${(html.length / 1024).toFixed(0)} kB`);
if (!process.argv.includes('--no-figures')) await take_figures();
